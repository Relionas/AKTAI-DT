NORMATIVE_NOTE = ("Источник — официальный текст акта на adilet.zan.kz. Результат — подсказка для проверки "
                  "человеком, а не юридическое или дисциплинарное заключение.")


def _short_ref(reference: str) -> str:
    """'Правила … № 231, глава 2, п. 22' -> 'Правила № 231, глава 2, п. 22' для текста описания."""
    if "№ 231" in reference and reference.startswith("Правила осуществления"):
        return "Правила № 231" + reference.split("№ 231", 1)[1]
    if reference.startswith("Правила организации охраны"):
        return "Правила № 14" + reference.split("№ 14", 1)[1].split(";")[0]
    return reference


def _describe(info: dict, item: dict) -> str:
    t = item.get("timecode_sec")
    when = f"{t} с" if t is not None else "момент не определён"
    ref = _short_ref(info["reference"])
    from_detector = item.get("evidence_source", "temporal_detector") == "temporal_detector" and info.get("observation")
    if from_detector:
        return (f"{when}: {info['observation']}. Почему это может быть нарушением: {info['why']} ({ref}). "
                f"Проверьте: {info['check']}.")
    return (f"Модель по признакам всего ролика указывает на возможный тип «{info['name']}». "
            f"Точный момент не локализован, кадр на {when} ориентировочный. "
            f"Проверьте: {info['check']}. Почему это может быть нарушением: {info['why']} ({ref}).")


def enrich_violation(violation: dict) -> dict:
    item = deepcopy(violation)
    code = str(item.get("type", "")).strip().lower()
    info = VIOLATION_CATALOG.get(code)
    item["type_code"] = code
    if not info:
        item.setdefault("description", "Модель обнаружила возможное нарушение; требуется проверка оператором.")
        item["rule_reference"] = "Не определён; требуется проверка оператором"
        item["visual_limit"] = "Вывод модели требует проверки оператором."
        return item
    item["type"] = info["name"]
    item["title"] = info["name"]
    item["description"] = _describe(info, item)
    item["details"] = info["check"]
    item["rule_reference"] = info["reference"]
    if "№ 231" in info["reference"]:
        item["rule_source_url"] = RULES_231_URL
    item["visual_limit"] = info["visual_limit"]
    item["normative_note"] = NORMATIVE_NOTE
    return item


def enrich_result(result: dict) -> dict:
    item = dict(result)
    item["violations"] = [enrich_violation(v) for v in result.get("violations", [])]
    return item


