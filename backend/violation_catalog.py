def enrich_violation(violation: dict) -> dict:
    """Return UI/API fields from a controlled catalog; preserve upstream evidence."""
    from copy import deepcopy
    item = deepcopy(violation)
    info = VIOLATION_CATALOG.get(str(item.get("type", "")).strip().lower())
    if not info:
        item.setdefault("rule_reference", "Не указан; требуется проверка источника")
        item.setdefault("visual_limit", "Вывод модели требует проверки оператором.")
        return item
    item["title"] = info["title"]
    item["description"] = info["description"]
    item["details"] = info["evidence_cue"]
    item["rule_reference"] = info["reference"]
    item["visual_limit"] = info["visual_limit"]
    item["normative_note"] = "Ссылка дана по предоставленным материалам проекта; проверьте действующую редакцию официального акта."
    return item


def enrich_result(result: dict) -> dict:
    item = dict(result)
    item["violations"] = [enrich_violation(v) for v in result.get("violations", [])]
    return item

